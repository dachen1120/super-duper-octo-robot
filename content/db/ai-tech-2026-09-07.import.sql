begin
  select id into v_industry from public.industries where slug = 'ai-tech';
  if v_industry is null then raise exception 'industry not found: %', 'ai-tech'; end if;

  insert into public.content_batches
    (industry_id, brief_date, status, title, title_en, full_audio_url, duration_ms, model, published_at)
  values
    (v_industry,
     (j->>'generatedAt')::date,
     'published',
     j->'dialogue'->>'title',
     j->'dialogue'->>'titleEn',
     j->'dialogue'->'audio'->>'src',
     (j->'dialogue'->'audio'->>'durationMs')::int,
     'manual-sample',
     now())
  on conflict (industry_id, brief_date) do update set
    status = excluded.status,
    title = excluded.title,
    title_en = excluded.title_en,
    full_audio_url = excluded.full_audio_url,
    duration_ms = excluded.duration_ms,
    model = excluded.model,
    published_at = excluded.published_at
  returning id into v_batch;

  -- 幂等：先清旧内容（用户统计/收藏等引用会按 FK 规则级联或置空）
  delete from public.dialogue_turns where batch_id = v_batch;
  delete from public.news_items where batch_id = v_batch;

  -- news
  for v_idx in 0 .. jsonb_array_length(j->'news') - 1 loop
    insert into public.news_items
      (batch_id, importance, headline_zh, headline_en, summary_zh, summary_en, tags, source_name, source_url, published_at)
    values
      (v_batch,
       (j->'news'->v_idx->>'importance')::int,
       j->'news'->v_idx->>'headline',
       j->'news'->v_idx->>'headlineEn',
       j->'news'->v_idx->>'summary',
       j->'news'->v_idx->>'summaryEn',
       coalesce(array(select jsonb_array_elements_text(j->'news'->v_idx->'tags')), '{}'::text[]),
       j->'news'->v_idx->>'source',
       j->'news'->v_idx->>'sourceUrl',
       (j->'news'->v_idx->>'updatedAt')::timestamptz);
  end loop;

  -- turns（relatedNewsId 末尾数字 = news importance）
  for v_idx in 0 .. jsonb_array_length(j->'dialogue'->'turns') - 1 loop
    v_rel := null;
    if (j->'dialogue'->'turns'->v_idx->>'relatedNewsId') is not null then
      v_rel := substring(j->'dialogue'->'turns'->v_idx->>'relatedNewsId' from '[0-9]+$')::int;
    end if;
    insert into public.dialogue_turns
      (batch_id, related_news_id, seq_no, speaker, text_en, text_zh, glosses, grammar, audio_url, start_ms, end_ms)
    values
      (v_batch,
       case when v_rel is not null
            then (select n.id from public.news_items n where n.batch_id = v_batch and n.importance = v_rel limit 1)
            else null end,
       v_idx + 1,
       j->'dialogue'->'turns'->v_idx->>'speaker',
       j->'dialogue'->'turns'->v_idx->>'en',
       j->'dialogue'->'turns'->v_idx->>'zh',
       coalesce(j->'dialogue'->'turns'->v_idx->'glosses', '[]'::jsonb),
       coalesce(j->'dialogue'->'turns'->v_idx->'grammar', '{}'::jsonb),
       j->'dialogue'->'turns'->v_idx->'audio'->>'src',
       (j->'dialogue'->'turns'->v_idx->'audio'->>'startMs')::int,
       (j->'dialogue'->'turns'->v_idx->'audio'->>'endMs')::int);
  end loop;
end
